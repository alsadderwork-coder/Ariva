namespace Ariva.UnitTests.Messaging;

/// <summary>
/// ARV-083b (CWE-269, CWE-285; ASVS 5.0 V13.2.1, V13.2.2): each host's Kafka principal (<see cref="KafkaAccess"/>) is granted
/// exactly what the code produces and consumes. The reads are what each host's composition root declares (its MassTransit
/// topic endpoints and the Stream engine's raw consumer, read from the booted host) and what the topic descriptions say; the
/// writes are every event type's topic (through the outbox, which every host relays, or directly, which Ingest's sensing sink
/// alone does) and every dead-letter topic the catalog provisions; no host reads a dead letter; and the deployment guide's
/// kafka-acls listing is the manifest's (regenerate it with ARIVA_UPDATE_ACLS=1).
/// </summary>
[Collection(HostCollection.Name)]
public sealed class KafkaAccessTests
{
    #region Fields

    private const string WikiStart = "<!-- kafka-acls:start (generated by KafkaAccessTests, do not edit) -->";
    private const string WikiEnd = "<!-- kafka-acls:end -->";
    private static readonly bool Update = Environment.GetEnvironmentVariable("ARIVA_UPDATE_ACLS") == "1";

    #endregion

    #region Hosts

    public static TheoryData<string, string> Hosts => new()
    {
        { ArivaHosts.Main, "main" }, { ArivaHosts.Ingest, "ingest" }, { ArivaHosts.Stream, "stream" }, { ArivaHosts.Cronz, "cronz" },
        { ArivaHosts.Integration, "integration" }
    };

    #endregion

    #region Reads

    [Theory]
    [MemberData(nameof(Hosts))]
    public async Task Reads_Should_BeWhatTheHostDeclares_When_ItIsBooted(string host, string service)
    {
        // The test output holds one host's appsettings.service.json (the last copied), so each host's own service name is given
        // here as its own file gives it (checked below).
        var file = System.Text.Json.Nodes.JsonNode.Parse(File.ReadAllText(RepositoryPaths.Resolve($"Platform/Backplane/Ariva.Api.{host}/appsettings.service.json")));
        file?["Kafka"]?["ServiceName"]?.GetValue<string>().Should().Be(service, "{0}'s groups are named after its service", host);
        await using var app = ArivaHosts.Create(host, configure: builder => builder.UseSetting("Kafka:ServiceName", service));

        var declared = app.Services.GetRequiredService<DeclaredConsumers>().Consumers;

        declared.Select(c => (c.Topic, c.Group, c.Raw)).Should().BeEquivalentTo(KafkaAccess.For(service).Reads.Select(r => (r.Topic, r.Group, r.Raw)),
            "{0}'s principal reads the topics and joins the groups its composition root declares, no more", host);
    }

    [Fact]
    public void Reads_Should_BeTheTopicDescriptionsConsumers()
    {
        var described = TopicDescriptions.All.SelectMany(d => d.Value.Consumers.Select(c => (Service: c.Service, Topic: d.Key, c.GroupId))).ToList();

        foreach (var service in KafkaAccess.Hosts)
        {
            KafkaAccess.For(service).Reads.Select(r => (r.Topic, r.Group)).Distinct()
                .Should().BeEquivalentTo(described.Where(d => d.Service == service).Select(d => (d.Topic, Group: d.GroupId)), "the AsyncAPI document names {0}'s groups", service);
        }
    }

    [Fact]
    public void NoHost_Should_ReadADeadLetterTopic_When_OnlyOperatorsMay()
    {
        foreach (var host in KafkaAccess.All)
            host.ReadTopics.Should().NotContain(t => t.EndsWith(KafkaTopics.DeadLetterSuffix, StringComparison.Ordinal), "only the operators and the replay tool read dead letters");
        KafkaAccess.Operators.Should().BeEquivalentTo(KafkaAccess.DeadLetterTopics, "the operators read every dead-letter topic");
    }

    #endregion

    #region Writes

    [Fact]
    public void Writes_Should_BeEveryEventTypesTopic_When_ProducedThroughTheOutboxOrDirectly()
    {
        var produced = KafkaAccess.OutboxTopics.Concat(KafkaAccess.DirectTopics.Values.SelectMany(t => t)).ToList();

        produced.Should().OnlyHaveUniqueItems("a topic is produced through the outbox or directly, not both");
        produced.Should().BeEquivalentTo(AsyncApiDocument.EventTypes.Keys, "every [KafkaTopic] event type is produced, and nothing else (the reserved topics have none)");
    }

    [Fact]
    public void DirectTopics_Should_BeIngestsSensingSink_When_NothingElseTakesTheBus()
    {
        // Only the sensing sink takes ISvcMessageBus (KafkaMessageBus implements it); every other producer writes to the outbox.
        var takers = typeof(KafkaAccess).Assembly.GetTypes()
            .Where(t => t.GetConstructors(BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance)
                .Any(c => c.GetParameters().Any(p => p.ParameterType == typeof(ISvcMessageBus))))
            .Select(t => t.Name);
        takers.Should().BeEquivalentTo(["MessageBusSensingSink"], "no other service publishes directly");

        var sensing = AsyncApiDocument.EventTypes.Where(e => typeof(SensingBatch).IsAssignableFrom(e.Value) || e.Value == typeof(DeviceHealthReported)).Select(e => e.Key);
        KafkaAccess.DirectTopics.Keys.Should().Equal(["ingest"]);
        KafkaAccess.DirectTopics["ingest"].Should().BeEquivalentTo(sensing, "the sink sends the sensing batches and the device health reports");
    }

    [Theory]
    [MemberData(nameof(Hosts))]
    public async Task SensingSink_Should_BeIngestsAlone_When_TheHostIsBooted(string host, string service)
    {
        await using var app = ArivaHosts.Create(host);

        var sink = app.Services.GetService<ISensingSink>();

        (sink is not null).Should().Be(KafkaAccess.DirectTopics.ContainsKey(service), "{0} sends directly only if it has the sensing sink", host);
    }

    [Fact]
    public void EveryHost_Should_WriteTheOutboxAndEveryDeadLetter_When_AnyHostMayLeadTheRelay()
    {
        var provisioned = TopicCatalog.ForProvisioning(new TopicDefaults { ProvisionAmanFeed = true }).Select(s => s.Name).ToList();
        provisioned.Where(t => t.EndsWith(KafkaTopics.DeadLetterSuffix, StringComparison.Ordinal))
            .Should().BeEquivalentTo(KafkaAccess.DeadLetterTopics, "a dead-letter topic for every topic, AMAN's feed included");

        foreach (var host in KafkaAccess.All)
        {
            host.Writes.Should().Contain(KafkaAccess.OutboxTopics, "{0} may lead the outbox relay", host.Service);
            host.Writes.Should().Contain(KafkaAccess.DeadLetterTopics, "{0} may send a dead letter another host kept", host.Service);
            host.Writes.Should().OnlyContain(t => KafkaProduce.IsProducible(t) && provisioned.Contains(t), "{0} writes Ariva's own provisioned topics only", host.Service);
            host.Writes.Should().NotContain(t => t.StartsWith("aman.", StringComparison.Ordinal), "AMAN's feed is AMAN's to write");
            host.Writes.Except(KafkaAccess.OutboxTopics).Except(KafkaAccess.DeadLetterTopics)
                .Should().BeEquivalentTo(KafkaAccess.DirectTopics.GetValueOrDefault(host.Service) ?? [], "beyond the shared writes, {0} writes its direct topics alone", host.Service);
        }
    }

    [Fact]
    public void TopicsJob_Should_CreateUnderAriva_And_AmansFeedOnlyWhereItProvisionsIt()
    {
        KafkaAccess.TopicsJob(amanFeed: false).Should().BeEquivalentTo([(KafkaAccess.Operation.Create, "ariva."), (KafkaAccess.Operation.Describe, "ariva.")]);
        KafkaAccess.TopicsJob(amanFeed: true).Select(a => a.Prefix).Distinct().Should().BeEquivalentTo(["ariva.", "aman.feed."]);
        TopicCatalog.ForProvisioning(new TopicDefaults()).Should().OnlyContain(s => s.Name.StartsWith("ariva.", StringComparison.Ordinal),
            "without AMAN's feed the job creates Ariva's topics alone");
    }

    #endregion

    #region Listing

    [Fact]
    public void Listing_Should_GrantEveryPrincipalItsManifest()
    {
        var listing = KafkaAccess.Listing();

        foreach (var host in KafkaAccess.All)
        {
            var variable = "\"$" + host.Service.ToUpperInvariant() + "\"";
            var lines = listing.Split('\n').Where(l => l.Contains(variable, StringComparison.Ordinal)).ToList();
            lines.Should().ContainSingle(l => l.Contains("--operation Write", StringComparison.Ordinal), "one write grant for {0}", host.Service);
            lines.Should().HaveCount(host.Reads.Count == 0 ? 1 : 2, "{0} has a read grant only if it consumes", host.Service);
            foreach (var topic in (KafkaAccess.DirectTopics.GetValueOrDefault(host.Service) ?? []).Concat(host.ReadTopics).Concat(host.Groups))
                string.Join('\n', lines).Should().Contain(" " + topic, "{0}'s grants name {1}", host.Service, topic);
        }

        foreach (var topic in KafkaAccess.OutboxTopics.Concat(KafkaAccess.DeadLetterTopics))
            listing.Should().Contain(topic);
        listing.Should().NotContain("--operation All").And.NotContain("--topic=*").And.NotContain("--cluster", "no principal is given more than its topics and groups");
    }

    [Fact]
    public void WikiListing_Should_BeTheManifests()
    {
        var file = RepositoryPaths.Resolve("wiki/04-Deployment-Guide.md");
        var text = File.ReadAllText(file).ReplaceLineEndings("\n");
        var start = text.IndexOf(WikiStart, StringComparison.Ordinal);
        var end = text.IndexOf(WikiEnd, StringComparison.Ordinal);
        start.Should().BeGreaterThan(0, "the deployment guide holds the generated kafka-acls commands between their markers");
        end.Should().BeGreaterThan(start);
        var expected = text[..(start + WikiStart.Length)] + "\n```bash\n" + KafkaAccess.Listing() + "```\n" + text[end..];
        if (Update)
            File.WriteAllText(file, expected);

        text.Should().Be(expected, "the listing is generated from KafkaAccess; regenerate it with ARIVA_UPDATE_ACLS=1");
    }

    #endregion
}
