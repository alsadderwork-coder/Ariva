    #region Settings

    public static TheoryData<string, string, string, bool, string> ProductionUsers => new()
    {
        { "redis:6379,ssl=true", "", "", true, "Redis:Username must name*" },
        { "redis:6379,ssl=true", "default", "redis-secret-value", true, "Redis:Username must name*" },
        { "redis:6379,ssl=true,user=default,password=redis-secret-value", "", "", true, "Redis:Username must name*" },
        { "redis:6379,ssl=true", "ariva-main", "", true, "Redis:Password must be set*" },
        { "redis:6379,ssl=true", "ariva-main", "redis-secret-value", false, null },
        { "redis:6379,ssl=true,user=ariva-main,password=redis-secret-value", "", "", false, null }
    };

    [Theory]
    [MemberData(nameof(ProductionUsers))]
    public void ProductionCredentialProblem_Should_RefuseTheDefaultUserOrNoPassword_When_InProduction(string connection, string user, string password, bool refused,
        string message)
    {
        var settings = new RedisSettings { Enabled = true, ConnectionString = connection, Username = user, Password = password };

        var problem = settings.ProductionCredentialProblem();

        if (refused)
            problem.Should().Match(message).And.NotContain("redis-secret-value");
        else
            problem.Should().BeNull();
        new RedisSettings { Enabled = false, ConnectionString = connection }.ProductionCredentialProblem().Should().BeNull("Redis off signs in as nobody");
    }

    [Fact]
    public void Options_Should_SignInAsTheHostsOwnUser_When_ItsSettingsNameOne()
    {
        var options = new RedisSettings { ConnectionString = "redis:6379,user=shared,password=shared-secret-value", Username = "ariva-ingest", Password = "ingest-secret-value" }.Options();

        options.User.Should().Be("ariva-ingest", "the host's own user replaces the shared string's");
        string.Equals(options.Password, "ingest-secret-value", StringComparison.Ordinal).Should().BeTrue("the host's own password replaces the shared string's");
        new RedisSettings { ConnectionString = "redis:6379" }.Options().User.Should().BeNull("without a user the client signs in as nobody, as before");
        RedisSettings.NamesCredentials("redis:6379,ssl=true").Should().BeFalse();
        RedisSettings.NamesCredentials("redis:6379,password=shared-secret-value").Should().BeTrue();
        RedisSettings.NamesCredentials("redis:6379,user=ariva").Should().BeTrue();
    }

    [Fact]
    public void Options_Should_NeverSendConfig_NorUseTheClientsChannelOrKey_When_Built()
    {
        // The ARV-083b review: the client never sends CONFIG and uses neither a configuration channel nor a tie-breaker key, whatever
        // the connection string says, so no host's user needs CONFIG GET, a channel every client listens on or a key outside Ariva's.
        var options = new RedisSettings { ConnectionString = "redis:6379,configChannel=elsewhere,tiebreaker=elsewhere,$CONFIG=CONFIG" }.Options();

        options.ToString().Should().Contain("$CONFIG=", "CONFIG is out of the command map");
        options.ConfigurationChannel.Should().BeEmpty();
        options.TieBreaker.Should().BeEmpty();
    }

    #endregion

    #region Listing

    [Fact]
    public void WikiListing_Should_BeTheManifests()
    {
        var file = RepositoryPaths.Resolve("wiki/04-Deployment-Guide.md");
        var text = File.ReadAllText(file).ReplaceLineEndings("\n");
        var start = text.IndexOf(WikiStart, StringComparison.Ordinal);
        var end = text.IndexOf(WikiEnd, StringComparison.Ordinal);
        start.Should().BeGreaterThan(0, "the deployment guide holds the generated ACL SETUSER lines between their markers");
        end.Should().BeGreaterThan(start);
        var expected = text[..(start + WikiStart.Length)] + "\n" + Listing() + text[end..];
        if (Update)
            File.WriteAllText(file, expected);

        text.Should().Be(expected, "the lines are generated from RedisAccess; regenerate them with ARIVA_UPDATE_ACLS=1");
    }

    /// <summary>The lines wiki 04 lists: k8s-prd's, each user named after its host, each password as the hash the operator computes.</summary>
    private static string Listing()
    {
        var lines = RedisAccess.All(Instance, Environment)
            .Select(g => RedisAccess.SetUser(g, $"ariva-{g.Service}", $"<sha256 of api-{g.Service}'s password>"));
        return "```text\n" + string.Join('\n', lines) + "\n```\n";
    }

    #endregion

    #region Helpers

    private static Dictionary<string, RedisAccess.KeyAccess> Access(Dictionary<string, RedisAccess.HostGrant> grants, string pattern) =>
        grants.Values.SelectMany(g => g.Keys.Where(k => k.Pattern == pattern).Select(k => (g.Service, k.Access))).ToDictionary(p => p.Service, p => p.Access);

    private static IReadOnlyList<string> HoldersOf(Dictionary<string, RedisAccess.HostGrant> grants, string channel) =>
        [.. grants.Values.Where(g => g.Channels.Contains(channel)).Select(g => g.Service)];

    /// <summary>A Redis glob (only * here) as a regular expression.</summary>
    private static Regex Glob(string pattern) =>
        new("^" + Regex.Escape(pattern).Replace("\\*", ".*", StringComparison.Ordinal) + "$", RegexOptions.None, TimeSpan.FromSeconds(1));

    #endregion
}
