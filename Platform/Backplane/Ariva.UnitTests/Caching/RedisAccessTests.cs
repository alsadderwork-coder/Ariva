using System.Text.RegularExpressions;
using Ariva.Infra.Caching;
using Ariva.UnitTests.Setup;
using FluentAssertions;

namespace Ariva.UnitTests.Caching;

/// <summary>
/// ARV-083b (CWE-269, CWE-285, CWE-287; ASVS 5.0 V13.2.1, V13.2.2): each host's Redis ACL user (<see cref="RedisAccess"/>) is
/// granted the names the code builds (<see cref="RedisNames"/>, which every Redis key and channel of the code comes from) and the
/// commands its paths run, no more: no host but Stream writes a live snapshot, none but Main and Cronz reads one, none but Main
/// holds the relay's lease or the hub's backplane, none but Stream and Main is on a live channel, and none gets a key or channel
/// outside Ariva's instance name, a wildcard, a command category or a command that changes the server. A k8s-prd host signs in
/// as its own user, never the default one, and its user and password from its own settings replace the connection string's. The
/// deployment guide's ACL SETUSER lines are the manifest's (regenerate them with ARIVA_UPDATE_ACLS=1). RedisAclTests runs the
/// paths on a Redis with these users.
/// </summary>
public sealed class RedisAccessTests
{
    #region Fields

    private const string Instance = "ariva:";
    private const string Environment = "k8s-prd";
    private const string WikiStart = "<!-- redis-acls:start (generated by RedisAccessTests, do not edit) -->";
    private const string WikiEnd = "<!-- redis-acls:end -->";
    private static readonly bool Update = System.Environment.GetEnvironmentVariable("ARIVA_UPDATE_ACLS") == "1";

    /// <summary>
    /// Commands that change the server, read every key, the ACLs or the server's configuration (CONFIG GET reads the default
    /// user's password, the replication password and the TLS key passphrases: the ARV-083b review), or run a script other than
    /// Main's lease: no host gets any.
    /// </summary>
    private static readonly string[] Dangerous =
    [
        "flushall", "flushdb", "keys", "scan", "config", "config|get", "config|set", "config|rewrite", "config|resetstat", "acl", "debug", "shutdown", "monitor", "save", "bgsave",
        "bgrewriteaof", "replicaof", "slaveof", "migrate", "module", "function", "script|flush", "client|kill", "client|list", "eval_ro", "rename", "restore"
    ];

    #endregion

    #region Names

    [Fact]
    public void Names_Should_SitUnderTheInstanceName_And_KeepTheCacheApartFromTheLiveKeys()
    {
        var names = new[]
        {
            RedisNames.CacheKeyPrefix(Instance), RedisNames.BackplaneChannelPrefix(Instance, Environment), RedisNames.LiveZoneKey(Instance, "DMO/A-VIS"),
            RedisNames.LiveZoneKeyPrefix(Instance), RedisNames.LiveZonesChannel(Instance), RedisNames.LiveAlertsChannel(Instance),
            RedisNames.LiveRelayKey(Instance), RedisNames.SignalRChannelPrefix(Instance)
        };

        names.Should().OnlyContain(n => n.StartsWith(Instance, StringComparison.Ordinal), "Ariva never collides with AMAN on a shared Redis");
        RedisNames.LiveZoneKey(Instance, "DMO/A-VIS").Should().StartWith(RedisNames.LiveZoneKeyPrefix(Instance));
        foreach (var live in new[] { RedisNames.LiveZoneKey(Instance, "DMO/A-VIS"), RedisNames.LiveRelayKey(Instance) })
            Glob(RedisNames.CacheKeyPrefix(Instance) + "*").IsMatch(live).Should().BeFalse("the cache's grant never reaches {0}", live);
        foreach (var channel in new[] { RedisNames.LiveZonesChannel(Instance), RedisNames.LiveAlertsChannel(Instance), RedisNames.SignalRChannelPrefix(Instance) + "x" })
            Glob(RedisNames.BackplaneChannelPattern(Instance, Environment)).IsMatch(channel).Should().BeFalse("the backplane's grant never reaches {0}", channel);
        // The backplane's grant is its own environment's channel alone (the ARV-083b review): not k8s-prd2's, not a prefix of it.
        Glob(RedisNames.BackplaneChannelPattern(Instance, Environment)).IsMatch(Instance + Environment + ".Backplane:v2").Should().BeTrue("FusionCache 2's channel");
        foreach (var other in new[] { Instance + Environment + "2.Backplane:v2", Instance + Environment + "x", Instance + Environment + ".Other" })
            Glob(RedisNames.BackplaneChannelPattern(Instance, Environment)).IsMatch(other).Should().BeFalse("another environment's or kind's channel ({0})", other);
    }

    [Fact]
    public void Code_Should_BuildEveryRedisNameThroughRedisNames()
    {
        // A key or channel built from the instance name anywhere else would be outside every host's grant (the cache's own keys,
        // such as LiveZoneDirectory's, are FusionCache's and sit under the cache's prefix).
        var sources = Directory.EnumerateFiles(RepositoryPaths.Resolve("Platform/Backplane"), "*.cs", SearchOption.AllDirectories)
            .Where(f => !f.Contains($"{Path.DirectorySeparatorChar}bin{Path.DirectorySeparatorChar}", StringComparison.Ordinal) &&
                        !f.Contains($"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}", StringComparison.Ordinal) &&
                        !f.Contains("Tests", StringComparison.Ordinal) && !f.EndsWith("RedisNames.cs", StringComparison.Ordinal))
            .Where(f => Regex.IsMatch(File.ReadAllText(f), @"InstanceName\s*\}|InstanceName\s*\+|""signalr""", RegexOptions.None, TimeSpan.FromSeconds(1)))
            .Select(Path.GetFileName);

        sources.Should().BeEmpty("every Redis name comes from RedisNames, which RedisAccess grants");
    }

    #endregion

    #region Grants

    [Fact]
    public void Grants_Should_GiveEachLiveNameToItsHostsAlone()
    {
        var liveZones = RedisNames.LiveZoneKeyPrefix(Instance) + "*";
        var grants = RedisAccess.All(Instance, Environment).ToDictionary(g => g.Service);

        Access(grants, liveZones).Should().BeEquivalentTo(new Dictionary<string, RedisAccess.KeyAccess>
        {
            ["main"] = RedisAccess.KeyAccess.Read, ["cronz"] = RedisAccess.KeyAccess.Read, ["stream"] = RedisAccess.KeyAccess.Write
        }, "Stream writes the snapshots, Main and Cronz read them, Ingest and Integration never see them");
        Access(grants, RedisNames.LiveRelayKey(Instance)).Should().BeEquivalentTo(new Dictionary<string, RedisAccess.KeyAccess> { ["main"] = RedisAccess.KeyAccess.ReadWrite });
        HoldersOf(grants, RedisNames.LiveZonesChannel(Instance)).Should().BeEquivalentTo(["main", "stream"]);
        HoldersOf(grants, RedisNames.LiveAlertsChannel(Instance)).Should().BeEquivalentTo(["main", "stream"]);
        HoldersOf(grants, RedisNames.SignalRChannelPrefix(Instance) + "*").Should().BeEquivalentTo(["main"]);
        foreach (var grant in grants.Values)
        {
            grant.Keys.Should().ContainSingle(k => k.Pattern == RedisNames.CacheKeyPrefix(Instance) + "*" && k.Access == RedisAccess.KeyAccess.ReadWrite, "every host caches");
            grant.Channels.Should().Contain(RedisNames.BackplaneChannelPattern(Instance, Environment), "every host hears the cache's evictions");
        }

        grants.Values.Where(g => g.Commands.Contains("eval")).Select(g => g.Service).Should().Equal(["main"], "the relay's lease is the only script");
        grants.Values.Where(g => g.Commands.Contains("setex")).Select(g => g.Service).Should().Equal(["stream"], "Stream alone writes the snapshots");
        grants.Values.Where(g => g.Commands.Contains("set")).Select(g => g.Service).Should().Equal(["main"], "the lease's script alone sets a key");
    }

    [Fact]
    public void Grants_Should_GiveNoHostAWildcardACategoryOrAServerCommand()
    {
        foreach (var grant in RedisAccess.All(Instance, Environment))
        {
            grant.Commands.Should().OnlyContain(c => Regex.IsMatch(c, "^[a-z_]+(\\|[a-z_]+)?$", RegexOptions.None, TimeSpan.FromSeconds(1)),
                "{0} gets named commands, no category (+@...) and no wildcard", grant.Service);
            grant.Commands.Should().NotContain(c => Dangerous.Contains(c) || Dangerous.Contains(c.Split('|')[0]), "{0} changes no server state", grant.Service);
            grant.Commands.Should().OnlyHaveUniqueItems();
            grant.Keys.Should().OnlyContain(k => k.Pattern.StartsWith(Instance, StringComparison.Ordinal), "{0}'s keys are Ariva's alone (no tie-breaker key)", grant.Service);
            grant.Keys.Should().NotContain(k => k.Pattern == Instance + "*" || k.Pattern == "*", "{0} gets no whole key space", grant.Service);
            grant.Channels.Should().OnlyContain(c => c.StartsWith(Instance, StringComparison.Ordinal),
                "{0}'s channels are Ariva's alone (no client configuration channel, which every client of that Redis listens on)", grant.Service);
            grant.Channels.Should().NotContain(c => c == Instance + "*" || c == "*", "{0} gets no whole channel space", grant.Service);
        }
    }

    [Fact]
    public void SetUser_Should_ResetEveryRuleFirst_And_GrantTheManifestOnly()
    {
        var grant = RedisAccess.For("stream", Instance, Environment);

        var line = RedisAccess.SetUser(grant, "ariva-stream", "0123abcd");

        line.Should().StartWith("ACL SETUSER ariva-stream reset on #0123abcd resetchannels -@all ",
            "every earlier rule is dropped, the password is given as its hash, and nothing is allowed but what follows");
        line.Split(' ').Where(w => w.StartsWith('+')).Select(w => w[1..]).Should().Equal(grant.Commands);
        line.Should().Contain("%W~" + RedisNames.LiveZoneKeyPrefix(Instance) + "*").And.Contain("&" + RedisNames.LiveZonesChannel(Instance));
        line.Should().NotContain("allkeys").And.NotContain("allchannels").And.NotContain("+@").And.NotContain(" ~*").And.NotContain("nopass");
        var unknown = () => RedisAccess.For("simulation", Instance, Environment);
        unknown.Should().Throw<ArgumentOutOfRangeException>();
    }

