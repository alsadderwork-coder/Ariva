namespace Ariva.Core.Domain.Entities;

/// <summary>
/// The plan image of a level (ARV-018): a PNG, JPEG or sanitised SVG kept in file storage under a generated key, with
/// its scale (metres per pixel) and the pixel where the level's floor origin lies, so zones and sensors in metres can
/// be drawn on it. One live plan per level; a new upload replaces the previous one.
/// </summary>
public class FloorPlan : BaseSoftDeletableEntity<FloorPlan>, ISiteBound
{
    public const long MaxBytes = 20L * 1024 * 1024;

    /// <summary>
    /// The longest file name kept (ARV-153): the column is varchar(200), and PostgreSQL counts code points, not text
    /// elements, so one letter with 300 combining marks is 301 characters to it however short it looks.
    /// </summary>
    public const int MaxFileNameLength = 200;

    /// <summary>The fixed refusal of a name longer than <see cref="MaxFileNameLength"/> code points (TopologyErrors.FileNameTooLong).</summary>
    public const string FileNameTooLongMessage = "The file name is at most 200 characters, each accent or other combining mark counted as one.";

    /// <summary>
    /// True when a file name fits the column: none, or at most <see cref="MaxFileNameLength"/> code points (a surrogate
    /// pair counts once, each combining mark once). Checked on its UTF-16 length first, so a long text is never walked.
    /// </summary>
    public static bool FileNameFits(string name) =>
        name is null || (name.Length <= 2 * MaxFileNameLength && name.EnumerateRunes().Count() <= MaxFileNameLength);

    /// <summary>
    /// True when a file name holds no path and nothing a reader cannot see (ARV-018, ARV-153; one rule since ARV-162): no
    /// slash, backslash, <c>..</c> or colon, and no lone surrogate, control or format character, each judged per code point
    /// (<see cref="Components.DisplayText.IsClean"/>), so a tag character outside the basic plane is refused like a
    /// right-to-left override. The upload, the site configuration import and export and the pre-pilot check all call it.
    /// </summary>
    public static bool HasSafeFileNameCharacters(string name) =>
        name is not null && !name.Contains('/') && !name.Contains('\\') && !name.Contains("..", StringComparison.Ordinal) && !name.Contains(':') &&
        Components.DisplayText.IsClean(name);

    /// <summary>
    /// A file name the floor plan rules take (ARV-162): blank (the upload stores "floor-plan" instead), or safe characters
    /// (<see cref="HasSafeFileNameCharacters"/>) and at most <see cref="MaxFileNameLength"/> code points after trimming.
    /// </summary>
    public static bool IsSafeFileName(string name) =>
        string.IsNullOrWhiteSpace(name) || (HasSafeFileNameCharacters(name) && FileNameFits(name.Trim()));

    protected FloorPlan()
    {
    }

    public FloorPlan(Level level, string storageKey, string contentType, long sizeBytes, string sha256, string originalFileName,
        int? widthPixels, int? heightPixels, double metresPerPixel, double originX, double originY)
    {
        ArgumentNullException.ThrowIfNull(level);
        ArgumentException.ThrowIfNullOrWhiteSpace(storageKey);
        ArgumentException.ThrowIfNullOrWhiteSpace(contentType);
        if (sizeBytes is <= 0 or > MaxBytes)
            throw new ArgumentOutOfRangeException(nameof(sizeBytes), sizeBytes, "A floor plan is at most 20 MB.");
        // The last line before the column: a name that does not fit is refused here, never at the insert (ARV-153).
        if (!FileNameFits(originalFileName))
            throw new ArgumentException(FileNameTooLongMessage, nameof(originalFileName));
        Level = level;
        SiteCode = level.SiteCode;
        StorageKey = storageKey;
        ContentType = contentType;
        SizeBytes = sizeBytes;
        Sha256 = sha256;
        OriginalFileName = originalFileName;
        WidthPixels = widthPixels;
        HeightPixels = heightPixels;
        Calibrate(metresPerPixel, originX, originY);
    }

    public virtual Level Level { get; protected set; }
    public virtual string SiteCode { get; protected set; }

    /// <summary>Generated by Ariva (never the uploaded file name), for example "0199...a1.png".</summary>
    public virtual string StorageKey { get; protected set; }

    public virtual string ContentType { get; protected set; }
    public virtual long SizeBytes { get; protected set; }

    /// <summary>SHA-256 (hex) of the stored bytes, after SVG sanitising.</summary>
    public virtual string Sha256 { get; protected set; }

    /// <summary>The uploaded name, for display only; never used as a path.</summary>
    public virtual string OriginalFileName { get; protected set; }

    public virtual int? WidthPixels { get; protected set; }
    public virtual int? HeightPixels { get; protected set; }
    public virtual double MetresPerPixel { get; protected set; }

    /// <summary>The pixel (from the image's top left) where the level's floor origin (0, 0) lies.</summary>
    public virtual double OriginX { get; protected set; }

    public virtual double OriginY { get; protected set; }

    /// <summary>Sets the scale and origin, for example after aligning the plan to two surveyed reference points.</summary>
    public virtual void Calibrate(double metresPerPixel, double originX, double originY)
    {
        if (!double.IsFinite(metresPerPixel) || metresPerPixel <= 0 || metresPerPixel > 10)
            throw new ArgumentOutOfRangeException(nameof(metresPerPixel), metresPerPixel, "The scale is more than 0 and at most 10 metres per pixel.");
        if (!double.IsFinite(originX) || !double.IsFinite(originY) || Math.Abs(originX) > 1_000_000 || Math.Abs(originY) > 1_000_000)
            throw new ArgumentOutOfRangeException(nameof(originX), "The origin is a pixel within one million of the image.");
        MetresPerPixel = metresPerPixel;
        OriginX = originX;
        OriginY = originY;
    }
}
